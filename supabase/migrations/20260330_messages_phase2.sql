create or replace function public.get_my_unread_message_count()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(x.unread_count), 0)::int
  from (
    select count(m.id)::int as unread_count
    from public.message_thread_participants mtp
    join public.messages m
      on m.thread_id = mtp.thread_id
    where mtp.user_id = auth.uid()
      and coalesce(mtp.is_muted, false) = false
      and coalesce(mtp.thread_folder, 'inbox') = 'inbox'
      and m.deleted_at is null
      and m.sender_user_id <> auth.uid()
      and m.id > coalesce(mtp.last_read_message_id, 0)
    group by mtp.thread_id
  ) x;
$$;

create or replace function public.list_my_message_threads()
returns table (
  thread_id bigint,
  thread_kind text,
  other_user_id uuid,
  other_display_name text,
  other_avatar_url text,
  last_message_id bigint,
  last_message_body text,
  last_message_created_at timestamptz,
  last_message_sender_user_id uuid,
  unread_count integer,
  can_reply boolean,
  thread_folder text,
  is_starred boolean,
  is_muted boolean,
  other_last_read_message_id bigint,
  other_last_read_at timestamptz,
  other_last_seen_at timestamptz,
  other_is_online boolean,
  is_blocked_by_me boolean,
  has_blocking boolean
)
language sql
stable
security definer
set search_path = public
as $$
  with my_threads as (
    select
      mt.id,
      mt.thread_kind,
      mtp.thread_folder,
      mtp.is_starred,
      mtp.is_muted
    from public.message_threads mt
    join public.message_thread_participants mtp
      on mtp.thread_id = mt.id
    where mtp.user_id = auth.uid()
      and coalesce(mtp.is_archived, false) = false
  ),
  other_participants as (
    select
      mt.id as thread_id,
      mt.thread_kind,
      mt.thread_folder,
      mt.is_starred,
      mt.is_muted,
      mtp.user_id as other_user_id,
      mtp.last_read_message_id as other_last_read_message_id,
      mtp.last_read_at as other_last_read_at
    from my_threads mt
    join public.message_thread_participants mtp
      on mtp.thread_id = mt.id
    where mtp.user_id <> auth.uid()
  ),
  last_messages as (
    select distinct on (m.thread_id)
      m.thread_id,
      m.id as last_message_id,
      m.body as last_message_body,
      m.created_at as last_message_created_at,
      m.sender_user_id as last_message_sender_user_id
    from public.messages m
    where m.deleted_at is null
    order by m.thread_id, m.created_at desc, m.id desc
  ),
  unread as (
    select
      mtp.thread_id,
      count(m.id)::int as unread_count
    from public.message_thread_participants mtp
    left join public.messages m
      on m.thread_id = mtp.thread_id
     and m.deleted_at is null
     and m.sender_user_id <> auth.uid()
     and m.id > coalesce(mtp.last_read_message_id, 0)
    where mtp.user_id = auth.uid()
    group by mtp.thread_id
  )
  select
    op.thread_id,
    op.thread_kind,
    op.other_user_id,
    up.display_name as other_display_name,
    up.avatar_url as other_avatar_url,
    lm.last_message_id,
    lm.last_message_body,
    lm.last_message_created_at,
    lm.last_message_sender_user_id,
    coalesce(u.unread_count, 0) as unread_count,
    (
      op.thread_kind = 'connected_dm'
      and not public.is_user_blocked_between(auth.uid(), op.other_user_id)
    ) as can_reply,
    op.thread_folder,
    op.is_starred,
    op.is_muted,
    op.other_last_read_message_id,
    op.other_last_read_at,
    pr.last_seen_at as other_last_seen_at,
    (pr.last_seen_at is not null and pr.last_seen_at >= now() - interval '5 minutes') as other_is_online,
    exists (
      select 1
      from public.blocked_users bu
      where bu.blocker_user_id = auth.uid()
        and bu.blocked_user_id = op.other_user_id
    ) as is_blocked_by_me,
    public.is_user_blocked_between(auth.uid(), op.other_user_id) as has_blocking
  from other_participants op
  left join public.user_profiles up
    on up.user_id = op.other_user_id
  left join last_messages lm
    on lm.thread_id = op.thread_id
  left join unread u
    on u.thread_id = op.thread_id
  left join public.user_presence pr
    on pr.user_id = op.other_user_id
  order by
    case when coalesce(u.unread_count, 0) > 0 and coalesce(op.is_starred, false) then 0
         when coalesce(u.unread_count, 0) > 0 then 1
         when coalesce(op.is_starred, false) then 2
         else 3 end asc,
    coalesce(lm.last_message_created_at, now()) desc,
    op.thread_id desc;
$$;

create or replace function public.list_thread_messages(
  p_thread_id bigint,
  p_limit integer default 100
)
returns table (
  id bigint,
  thread_id bigint,
  sender_user_id uuid,
  body text,
  created_at timestamptz,
  sender_display_name text,
  sender_avatar_url text,
  reply_to_message_id bigint,
  reply_to_body text,
  reply_to_sender_user_id uuid,
  reaction_summary jsonb
)
language sql
stable
security definer
set search_path = public
as $$
  with thread_messages as (
    select
      m.id,
      m.thread_id,
      m.sender_user_id,
      m.body,
      m.created_at,
      m.reply_to_message_id,
      rm.body as reply_to_body,
      rm.sender_user_id as reply_to_sender_user_id
    from public.messages m
    left join public.messages rm
      on rm.id = m.reply_to_message_id
    where m.thread_id = p_thread_id
      and m.deleted_at is null
      and exists (
        select 1
        from public.message_thread_participants mtp
        where mtp.thread_id = p_thread_id
          and mtp.user_id = auth.uid()
      )
    order by m.created_at asc, m.id asc
    limit greatest(coalesce(p_limit, 100), 1)
  ),
  reactions as (
    select
      mr.message_id,
      jsonb_agg(
        jsonb_build_object(
          'emoji', mr.emoji,
          'count', mr.cnt,
          'reactedByMe', mr.reacted_by_me
        )
        order by mr.emoji
      ) as reaction_summary
    from (
      select
        r.message_id,
        r.emoji,
        count(*)::int as cnt,
        bool_or(r.user_id = auth.uid()) as reacted_by_me
      from public.message_reactions r
      where r.message_id in (select tm.id from thread_messages tm)
      group by r.message_id, r.emoji
    ) mr
    group by mr.message_id
  )
  select
    tm.id,
    tm.thread_id,
    tm.sender_user_id,
    tm.body,
    tm.created_at,
    up.display_name as sender_display_name,
    up.avatar_url as sender_avatar_url,
    tm.reply_to_message_id,
    tm.reply_to_body,
    tm.reply_to_sender_user_id,
    coalesce(rx.reaction_summary, '[]'::jsonb) as reaction_summary
  from thread_messages tm
  left join public.user_profiles up
    on up.user_id = tm.sender_user_id
  left join reactions rx
    on rx.message_id = tm.id
  order by tm.created_at asc, tm.id asc;
$$;

