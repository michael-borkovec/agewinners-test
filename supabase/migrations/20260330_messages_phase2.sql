-- Messaging phase 2:
-- - folders: inbox / blocked
-- - starred / muted thread preferences
-- - user blocking for message threads
-- - thread reports for moderators
-- - reply-to and reactions
-- - presence + read receipt metadata

alter table public.message_thread_participants
  add column if not exists thread_folder text not null default 'inbox'
    check (thread_folder in ('inbox', 'blocked')),
  add column if not exists is_starred boolean not null default false;

create index if not exists message_thread_participants_user_folder_idx
  on public.message_thread_participants (user_id, thread_folder, is_starred, thread_id);

alter table public.messages
  add column if not exists reply_to_message_id bigint null references public.messages(id) on delete set null;

create index if not exists messages_reply_to_idx
  on public.messages (reply_to_message_id)
  where reply_to_message_id is not null;

create table if not exists public.message_reactions (
  message_id bigint not null references public.messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  emoji text not null check (char_length(trim(emoji)) between 1 and 16),
  created_at timestamptz not null default now(),
  primary key (message_id, user_id, emoji)
);

create index if not exists message_reactions_message_idx
  on public.message_reactions (message_id, created_at desc);

create table if not exists public.blocked_users (
  blocker_user_id uuid not null references auth.users(id) on delete cascade,
  blocked_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  reason text null,
  primary key (blocker_user_id, blocked_user_id),
  constraint blocked_users_not_self check (blocker_user_id <> blocked_user_id)
);

create index if not exists blocked_users_blocked_idx
  on public.blocked_users (blocked_user_id, blocker_user_id);

create table if not exists public.message_thread_reports (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.message_threads(id) on delete cascade,
  reporter_user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  reason text not null,
  details text null,
  status text not null default 'open' check (status in ('open', 'accepted', 'rejected')),
  admin_note text null,
  reviewed_at timestamptz null,
  reviewed_by uuid null references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists message_thread_reports_thread_status_idx
  on public.message_thread_reports (thread_id, status, created_at desc);

create index if not exists message_thread_reports_reporter_idx
  on public.message_thread_reports (reporter_user_id, created_at desc);

create table if not exists public.user_presence (
  user_id uuid primary key references auth.users(id) on delete cascade,
  last_seen_at timestamptz not null default now()
);

alter table public.message_reactions enable row level security;
alter table public.blocked_users enable row level security;
alter table public.message_thread_reports enable row level security;
alter table public.user_presence enable row level security;

