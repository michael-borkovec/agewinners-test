create or replace function public.is_user_blocked_between(
  p_user_a uuid,
  p_user_b uuid
)
returns boolean
language sql
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.blocked_users bu
    where (bu.blocker_user_id = p_user_a and bu.blocked_user_id = p_user_b)
       or (bu.blocker_user_id = p_user_b and bu.blocked_user_id = p_user_a)
  );
$$;

create or replace function public.touch_my_presence()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  insert into public.user_presence (user_id, last_seen_at)
  values (v_auth_user_id, now())
  on conflict (user_id) do update
    set last_seen_at = excluded.last_seen_at;
end;
$$;

create or replace function public.set_message_thread_preferences(
  p_thread_id bigint,
  p_is_muted boolean default null,
  p_is_starred boolean default null,
  p_thread_folder text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  if p_thread_folder is not null and p_thread_folder not in ('inbox', 'blocked') then
    raise exception 'invalid_thread_folder';
  end if;

  update public.message_thread_participants
  set
    is_muted = coalesce(p_is_muted, is_muted),
    is_starred = coalesce(p_is_starred, is_starred),
    thread_folder = coalesce(p_thread_folder, thread_folder)
  where thread_id = p_thread_id
    and user_id = v_auth_user_id;

  if not found then
    raise exception 'thread_not_found';
  end if;
end;
$$;

create or replace function public.block_message_thread_user(
  p_thread_id bigint,
  p_other_user_id uuid,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  if p_other_user_id is null or p_other_user_id = v_auth_user_id then
    raise exception 'invalid_other_user';
  end if;

  if not exists (
    select 1
    from public.message_thread_participants mtp
    where mtp.thread_id = p_thread_id
      and mtp.user_id = v_auth_user_id
  ) then
    raise exception 'thread_not_found';
  end if;

  if not exists (
    select 1
    from public.message_thread_participants mtp
    where mtp.thread_id = p_thread_id
      and mtp.user_id = p_other_user_id
  ) then
    raise exception 'other_user_not_in_thread';
  end if;

  insert into public.blocked_users (blocker_user_id, blocked_user_id, reason)
  values (v_auth_user_id, p_other_user_id, nullif(trim(coalesce(p_reason, '')), ''))
  on conflict (blocker_user_id, blocked_user_id) do update
    set reason = excluded.reason;

  update public.message_thread_participants
  set thread_folder = 'blocked'
  where thread_id = p_thread_id
    and user_id = v_auth_user_id;
end;
$$;

create or replace function public.unblock_message_thread_user(
  p_thread_id bigint,
  p_other_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  delete from public.blocked_users
  where blocker_user_id = v_auth_user_id
    and blocked_user_id = p_other_user_id;

  update public.message_thread_participants
  set thread_folder = 'inbox'
  where thread_id = p_thread_id
    and user_id = v_auth_user_id;
end;
$$;

create or replace function public.report_message_thread(
  p_thread_id bigint,
  p_reason text,
  p_details text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_report_id bigint;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
  v_details text := nullif(trim(coalesce(p_details, '')), '');
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  if v_reason is null then
    raise exception 'bad_request_reason';
  end if;

  if not exists (
    select 1
    from public.message_thread_participants mtp
    where mtp.thread_id = p_thread_id
      and mtp.user_id = v_auth_user_id
  ) then
    raise exception 'thread_not_found';
  end if;

  insert into public.message_thread_reports (
    thread_id,
    reporter_user_id,
    reason,
    details,
    status
  )
  values (
    p_thread_id,
    v_auth_user_id,
    left(v_reason, 200),
    case when v_details is null then null else left(v_details, 2000) end,
    'open'
  )
  returning id into v_report_id;

  return v_report_id;
end;
$$;

create or replace function public.toggle_message_reaction(
  p_message_id bigint,
  p_emoji text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_emoji text := nullif(trim(coalesce(p_emoji, '')), '');
begin
  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  if v_emoji is null then
    raise exception 'empty_emoji';
  end if;

  if exists (
    select 1
    from public.message_reactions mr
    where mr.message_id = p_message_id
      and mr.user_id = v_auth_user_id
      and mr.emoji = v_emoji
  ) then
    delete from public.message_reactions
    where message_id = p_message_id
      and user_id = v_auth_user_id
      and emoji = v_emoji;
  else
    insert into public.message_reactions (message_id, user_id, emoji)
    values (p_message_id, v_auth_user_id, v_emoji);
  end if;
end;
$$;

create or replace function public.send_thread_message(
  p_thread_id bigint,
  p_body text,
  p_reply_to_message_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid;
  v_thread record;
  v_message_id bigint;
  v_other_user_id uuid;
  v_body text;
begin
  v_auth_user_id := auth.uid();

  if v_auth_user_id is null then
    raise exception 'not_authenticated';
  end if;

  select mt.*
    into v_thread
  from public.message_threads mt
  join public.message_thread_participants mtp
    on mtp.thread_id = mt.id
   and mtp.user_id = v_auth_user_id
  where mt.id = p_thread_id;

  if not found then
    raise exception 'thread_not_found';
  end if;

  v_body := nullif(trim(coalesce(p_body, '')), '');
  if v_body is null then
    raise exception 'empty_message';
  end if;

  if v_thread.thread_kind <> 'connected_dm' then
    raise exception 'thread_read_only';
  end if;

  select mtp.user_id
    into v_other_user_id
  from public.message_thread_participants mtp
  where mtp.thread_id = p_thread_id
    and mtp.user_id <> v_auth_user_id
  limit 1;

  if v_other_user_id is null then
    raise exception 'invalid_thread_participants';
  end if;

  if not public.are_users_connected(v_auth_user_id, v_other_user_id) then
    raise exception 'not_connected';
  end if;

  if public.is_user_blocked_between(v_auth_user_id, v_other_user_id) then
    raise exception 'thread_blocked';
  end if;

  if p_reply_to_message_id is not null and not exists (
    select 1
    from public.messages m
    where m.id = p_reply_to_message_id
      and m.thread_id = p_thread_id
      and m.deleted_at is null
  ) then
    raise exception 'invalid_reply_target';
  end if;

  insert into public.messages (thread_id, sender_user_id, body, reply_to_message_id)
  values (p_thread_id, v_auth_user_id, left(v_body, 4000), p_reply_to_message_id)
  returning id into v_message_id;

  return v_message_id;
end;
$$;

