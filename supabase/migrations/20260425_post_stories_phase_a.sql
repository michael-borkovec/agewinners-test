  to authenticated
  using (auth.uid() = reporter_user_id);

drop policy if exists "post_story_reports_insert_viewer" on public.post_story_reports;
create policy "post_story_reports_insert_viewer"
  on public.post_story_reports
  for insert
  to authenticated
